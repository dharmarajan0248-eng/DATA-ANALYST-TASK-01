import pandas as pd
import numpy as np
import matplotlib.pyplot as plt
import seaborn as sns
from sklearn.preprocessing import StandardScaler
from sklearn.cluster import KMeans
from sklearn.metrics import silhouette_score

# =====================================================================
# 1. DATA CLEANING
# =====================================================================
# File tab-separated (\t) hai is liye sep="\t" use kiya hai
df = pd.read_csv("/content/marketing_campaign.csv", sep="\t")

# Missing values ko Median se fill karna (Income column)
df['Income'] = df['Income'].fillna(df['Income'].median())

# Date format ko standard date-time mein tabdeel karna
df['Dt_Customer'] = pd.to_datetime(df['Dt_Customer'], format='%d-%m-%Y')

# Outliers ko remove karna (Umar 100 saal se kam aur Aamdani $200k se kam)
df['Age'] = 2026 - df['Year_Birth'] # Current year k mutabiq age
df = df[(df['Age'] < 100) & (df['Income'] < 200000)]

print("Step 1: Data Cleaning Completed. Rows left:", df.shape[0])


# =====================================================================
# 2. FEATURE ENGINEERING
# =====================================================================
# Tamam products ke kharchay ko mila kar 'Total_Spending' banana
df['Total_Spending'] = df[['MntWines', 'MntFruits', 'MntMeatProducts',
                           'MntFishProducts', 'MntSweetProducts', 'MntGoldProds']].sum(axis=1)

# Bachon aur teens ko mila kar 'Total_Children' banana
df['Total_Children'] = df['Kidhome'] + df['Teenhome']

# Marital Status ko simple 'Partner' ya 'Alone' mein badalna
df['Living_Status'] = df['Marital_Status'].replace({
    'Married': 'Partner', 'Together': 'Partner',
    'Single': 'Alone', 'Divorced': 'Alone', 'Widow': 'Alone', 'Alone': 'Alone',
    'Absurd': 'Alone', 'YOLO': 'Alone'
})

# Education ko categories mein badalna
df['Education_Level'] = df['Education'].replace({
    'Graduation': 'Graduate', 'PhD': 'Postgraduate', 'Master': 'Postgraduate',
    '2n Cycle': 'Undergraduate', 'Basic': 'Undergraduate'
})

print("Step 2: Feature Engineering Completed.")


# =====================================================================
# 3. EDA & VISUALIZATION
# =====================================================================
# 1. Income Distribution
plt.figure(figsize=(8, 4))
sns.histplot(df['Income'], kde=True, color='blue', bins=30)
plt.title('1. Customers Income Distribution')
plt.show()
# 2. Product Spending Breakdown
products = ['MntWines', 'MntFruits', 'MntMeatProducts', 'MntFishProducts', 'MntSweetProducts', 'MntGoldProds']
avg_spent = df[products].mean().sort_values(ascending=False)
plt.figure(figsize=(8, 4))
sns.barplot(x=avg_spent.values, y=avg_spent.index, palette='viridis')
plt.title('2. Average Spending per Product Category')
plt.show()
# 3. Income vs Spending Correlation
plt.figure(figsize=(8, 4))
sns.regplot(data=df, x='Income', y='Total_Spending', scatter_kws={'alpha':0.3}, line_kws={'color':'red'})
plt.title('3. Income vs Total Spending Correlation')
plt.show()
# 4. Marketing Campaign Success Rate
campaigns = ['AcceptedCmp1', 'AcceptedCmp2', 'AcceptedCmp3', 'AcceptedCmp4', 'AcceptedCmp5']
camp_success = df[campaigns].sum().sort_values(ascending=False)
plt.figure(figsize=(8, 4))
sns.barplot(x=camp_success.index, y=camp_success.values, palette='magma')
plt.title('4. Success Rate of Past Marketing Campaigns')
plt.show()
# Income aur Spending ka aapsi talluq dekhna

plt.figure(figsize=(10, 6))
sns.scatterplot(data=df, x='Income', y='Total_Spending', hue='Education_Level', alpha=0.7)
plt.title('Income vs Total Spending by Education Level')
plt.xlabel('Saalana Income ($)')
plt.ylabel('Total Spending ($)')
plt.savefig('income_vs_spending.png') # Graph image save ho jayegi
plt.show()

print("Step 3: EDA & Visualization Completed (Graph Saved).")


# =====================================================================
# 4. MACHINE LEARNING MODELS (Customer Segmentation)
# =====================================================================
# Clustering ke liye ahem features select karna
features = ['Age', 'Income', 'Total_Spending', 'Total_Children']
X = df[features]

# Data ko Scale karna taake bare numbers model ko disturb na karein
scaler = StandardScaler()
X_scaled = scaler.fit_transform(X)

# K-Means Clustering apply karna (4 Groups/Clusters banana)
kmeans = KMeans(n_clusters=4, random_state=42, n_init=10)
df['Cluster'] = kmeans.fit_predict(X_scaled)

print("Step 4: Machine Learning Model (K-Means) Trained successfully.")


# =====================================================================
# 5. MODEL EVALUATION
# =====================================================================
# Silhouette Score maloom karna (Yeh batata hai clustering kitni achhi hui)
score = silhouette_score(X_scaled, df['Cluster'])
print(f"Step 5: Model Evaluation - Silhouette Score: {score:.4f}")

# Har cluster (Group) ka profile analyze karna
cluster_profile = df.groupby('Cluster')[features].mean()
print("\n--- CUSTOMER GROUPS PROFILE (AVERAGE VALUES) ---")
print(cluster_profile.round(2))